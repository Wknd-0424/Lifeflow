-- Run once in the dedicated LifeFlow project's SQL editor.
BEGIN;
CREATE TABLE IF NOT EXISTS public.batches (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 donor text NOT NULL CHECK(length(trim(donor)) BETWEEN 1 AND 120),
 blood_group text NOT NULL CHECK(blood_group IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
 units integer NOT NULL CHECK(units>=0), collected date NOT NULL, expires date NOT NULL CHECK(expires>collected), created timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.requests (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 hospital text NOT NULL CHECK(length(trim(hospital)) BETWEEN 1 AND 120), contact text NOT NULL CHECK(length(trim(contact)) BETWEEN 1 AND 120),
 blood_group text NOT NULL CHECK(blood_group IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
 units integer NOT NULL CHECK(units BETWEEN 1 AND 1000), priority text NOT NULL CHECK(priority IN ('Normal','Urgent')),
 status text NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Fulfilled','Cancelled')), created timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.allocations(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,request_id integer NOT NULL REFERENCES public.requests(id),batch_id integer NOT NULL REFERENCES public.batches(id),units integer NOT NULL CHECK(units>0));
CREATE TABLE IF NOT EXISTS public.activity(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,description text NOT NULL,kind text NOT NULL,created timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS public.settings(key text PRIMARY KEY,value text);
CREATE INDEX IF NOT EXISTS batches_allocation_idx ON public.batches(blood_group,expires,id) WHERE units>0;
ALTER TABLE public.batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.allocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activity ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.batches, public.requests, public.allocations, public.activity, public.settings FROM anon, authenticated;
